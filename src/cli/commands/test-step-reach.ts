/**
 * `test-step-reach.ts`: which test files load which project files, so `boardsmith verify` runs each
 * mutant only against the test files that can reach it (#981).
 *
 * The unmutated run of the whole suite adds `REACH_SETUP` as a setup file. It asks V8, through
 * `node:inspector`, for every script the test file's worker parses (`Debugger.scriptParsed`, which
 * also names every script parsed before it asked), and writes each project file among them to the
 * test file's record as it happens, so a module first loaded in a late hook, by a dynamic import,
 * an `import.meta.glob` or a path built at run time is in it too. A mutant is served only through
 * Vite's `load` hook to the modules a test worker runs, and until its file is loaded a run goes
 * exactly as the unmutated one did, so a test file whose worker never loaded the file cannot be
 * changed by the mutant (for a test that loads the same modules every run).
 *
 * Where that cannot be shown, the test file runs for every mutant: it has no record (the inspector
 * was not available, or it never reached its first test), its record does not hold the test file
 * itself (a Vitest that runs files some way this does not see), or its worker ran another test file
 * first (`isolate: false`), whose modules it may use without loading them. A global setup runs
 * project code outside every worker and hands values to the tests, so with one every test file runs
 * for every mutant (`GLOBAL_SETUP_MARK`, written by the run's reporter).
 *
 * Code a test runs in plain Node outside its own worker (a child process, a worker thread) is not in
 * the record, and need not be: it loads files from disk, not through this run's Vite server, so it
 * never sees the mutant (#1488).
 */
import { promises as fs } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { readIfExists } from '../lib/read-if-exists.js';

/** The setup file (see the file comment). Reads where to write and the project's path from the environment. */
export const REACH_SETUP = `// Generated by boardsmith verify; removed when the check ends.
// Records every project file this test file's worker loads, so a mutant runs only against the tests that load it.
import { beforeAll } from 'vitest';

// A worker that ran another test file first keeps what that file loaded, and this file may use it.
const lines = globalThis.__boardsmithReach ? ['*'] : [];
globalThis.__boardsmithReach = true;
let node;
try {
  const [{ Session }, fs, url] = await Promise.all([import('node:inspector'), import('node:fs'), import('node:url')]);
  const session = new Session();
  session.connect();
  node = { session, fs, url };
} catch {
  // No inspector here (a browser, or Node's permission model), so no record: this file runs for every mutant.
}
let record;
if (node && lines.length === 0) {
  const root = process.env.BOARDSMITH_REACH_ROOT;
  node.session.on('Debugger.scriptParsed', ({ params }) => {
    const path = (params.url.startsWith('file://') ? node.url.fileURLToPath(params.url) : params.url).split('?')[0];
    if (!path.startsWith(root) || path.includes('/node_modules/')) return;
    if (record) node.fs.appendFileSync(record, path + '\\n');
    else lines.push(path);
  });
  const post = (method, params) => new Promise((resolve, reject) => node.session.post(method, params, (error) => (error ? reject(error) : resolve())));
  await post('Debugger.enable');
  // Debugger is on only to hear of each script; it must never stop at a \`debugger\` statement.
  await post('Debugger.setSkipAllPauses', { skip: true });
}
// The file's own task names it: a shared worker's expect state still names the file before.
beforeAll((file) => {
  if (!node) return;
  record = process.env.BOARDSMITH_REACH + '/' + encodeURIComponent(file.filepath);
  node.fs.appendFileSync(record, lines.map((line) => line + '\\n').join(''));
});
`;

/** The file the run's reporter writes in the record directory when any Vitest project has a global setup. */
export const GLOBAL_SETUP_MARK = 'global-setup';

/** Where the setup file writes, and the project whose files it records: settings for the unmutated run. */
export function reachEnv(reachDir: string, projectDir: string): Record<string, string> {
  return { BOARDSMITH_REACH: reachDir, BOARDSMITH_REACH_ROOT: projectDir + sep };
}

/**
 * The test files that can reach each project file, by absolute path, read from the records of the
 * unmutated run. `projectDir` is the project's real path; `testFiles` are the project paths of every
 * test file the run ran. `unrecorded` names those that run for every mutant (see the file comment).
 */
export async function readReach(
  reachDir: string,
  projectDir: string,
  testFiles: Iterable<string>,
): Promise<{ testsLoading(file: string): string[]; unrecorded: string[] }> {
  const globalSetup = (await readIfExists(join(reachDir, GLOBAL_SETUP_MARK), fs.stat)) !== undefined;
  const loads = new Map<string, Set<string> | 'every file'>();
  for (const test of testFiles) {
    const text = globalSetup ? undefined : await readIfExists(join(reachDir, encodeURIComponent(join(projectDir, test))), (p) => fs.readFile(p, 'utf-8'));
    const lines = text?.split('\n').filter(Boolean) ?? [];
    const paths = new Set(lines.map((p) => relative(projectDir, p).split(sep).join('/')));
    loads.set(test, text === undefined || lines.includes('*') || !paths.has(test) ? 'every file' : paths);
  }
  return {
    testsLoading: (file) => [...loads].filter(([, paths]) => paths === 'every file' || paths.has(file)).map(([test]) => join(projectDir, test)),
    unrecorded: [...loads].filter(([, paths]) => paths === 'every file').map(([test]) => test),
  };
}
